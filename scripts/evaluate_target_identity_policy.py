def synthetic_sequence(seed: str, length: int) -> str:
    """Version-stable synthetic sequence from indexed SHA-256 digests."""
    return "".join(
        AA[hashlib.sha256(f"{seed}|{index}".encode("ascii")).digest()[0] % len(AA)]
        for index in range(length)
    )


def _different_residue(aa: str, index: int) -> str:
    offset = (AA.index(aa) + 1 + (index % (len(AA) - 1))) % len(AA)
    replacement = AA[offset]
    return replacement if replacement != aa else AA[(offset + 1) % len(AA)]


def transformed_sequence(case: dict, reference: str) -> str:
    transform = case["transform"]
    if transform == "identity":
        return reference
    if transform == "terminal_truncation":
        left, right = case["left_trim"], case["right_trim"]
        return reference[left : len(reference) - right]
    if transform == "substitutions":
        sequence = list(reference)
        for position in case["positions"]:
            index = position - 1
            sequence[index] = _different_residue(sequence[index], index)
        return "".join(sequence)
    if transform == "deletion":
        start = case["start"]
        return reference[:start] + reference[start + case["length"] :]
    if transform == "insertion":
        position = case["position"]
        return reference[:position] + case["sequence"] + reference[position:]
    if transform == "homolog_substitutions":
        sequence = list(reference)
        for index in range(case["offset"], len(sequence), case["step"]):
            sequence[index] = _different_residue(sequence[index], index)
        return "".join(sequence)
    if transform == "local_segment":
        start = case["start"]
        return reference[start : start + case["length"]]
    if transform == "unrelated":
        return synthetic_sequence(case.get("seed", "unrelated-sequence-v1"), len(reference))
    if transform == "unknown_residues":
        sequence = list(reference)
        for index in range(case["offset"], len(sequence), case["step"]):
            sequence[index] = "X"
        return "".join(sequence)
    if transform == "recognized_mse":
        return reference
    raise ValueError(f"Unsupported fixture transform: {transform}")


def dbref_line(accession: str, chain_id: str, length: int) -> str:
    line = [" "] * 80
    line[0:6] = "DBREF "
    line[7:11] = "TEST"
    line[12] = " " if chain_id == "_" else chain_id
    line[14:18] = "   1"
    line[20:24] = f"{length:4d}"
    line[26:32] = "UNP   "
    line[33:41] = accession.ljust(8)
    return "".join(line)


def atom_line(serial: int, residue: str, chain_id: str, number: int, record="ATOM  ") -> str:
    line = [" "] * 80
    line[0:6] = record
    line[6:11] = f"{serial:5d}"
    line[12:16] = " CA "
    line[17:20] = residue
    line[21] = " " if chain_id == "_" else chain_id
    line[22:26] = f"{number:4d}"
    line[30:38] = f"{float(number):8.3f}"
    line[38:46] = f"{0.0:8.3f}"
    line[46:54] = f"{0.0:8.3f}"
    line[54:60] = f"{1.0:6.2f}"
    line[60:66] = f"{20.0:6.2f}"
    line[76:78] = " C"
    return "".join(line)


def synthetic_pdb_lines(sequence: str, chain_id="A", dbref=True, accession="P00533", transform=""):
    lines = []
    if dbref:
        lines.append(dbref_line(accession, chain_id, len(sequence)))
    elif transform == "extended":
        extended1 = [" "] * 80
        extended1[0:6] = "DBREF1"
        extended1[7:11] = "TEST"
        extended1[12] = " " if chain_id == "_" else chain_id
        extended1[14:18] = "   1"
        extended1[20:24] = f"{len(sequence):4d}"
        extended1[26:32] = "UNP   "
        lines.append("".join(extended1))
        extended2 = [" "] * 80
        extended2[0:6] = "DBREF2"
        extended2[7:11] = "TEST"
        extended2[12] = " " if chain_id == "_" else chain_id
        extended2[18:20] = "UN"
        extended2[20:35] = accession.ljust(15)
        lines.append("".join(extended2))

    residue_names = []
    mse_index = None
    if transform == "recognized_mse":
        mse_index = sequence.index("M")
    for index, aa in enumerate(sequence):
        if aa == "X":
            residue_name, record = "UNK", "ATOM  "
        elif index == mse_index:
            residue_name, record = "MSE", "HETATM"
        else:
            residue_name, record = AA3[aa], "ATOM  "
        residue_names.append(residue_name)
        lines.append(atom_line(index + 1, residue_name, chain_id, index + 1, record))
    return lines


def _make_evidence(case: dict, observed: str):
    chain_id = case.get("chain_id", "A")
    if case.get("transform") == "multiple_chains":
        lines = synthetic_pdb_lines("A", "A", accession="P00533")
        lines.extend(synthetic_pdb_lines("C", "B", accession="P56817"))
        return parse_pdb_identity(lines), {}, None, None
    if case.get("transform") == "conflicting_dbref":
        lines = synthetic_pdb_lines(observed, "A", accession="P00533")
        lines.append(dbref_line("P56817", "A", len(observed)))
        evidence = parse_pdb_identity(lines)
        evidence["chain_sequences"] = {"A": extract_pdb_chain_sequence(lines, "A")}
        return evidence, evidence["chain_sequences"], None, None

    record = case.get("dbref", True)
    extended = case.get("dbref_format") == "extended"
    dbref = record is True and not extended
    lines = synthetic_pdb_lines(
        observed, chain_id, dbref=dbref, accession=case.get("accession", "P00533"),
        transform="extended" if extended else "",
    )
    evidence = parse_pdb_identity(lines)
    chains = {chain_id: extract_pdb_chain_sequence(lines, chain_id)}
    evidence["chain_sequences"] = chains
    selected_chain = chain_id if len(evidence.get("chain_ids", [])) == 1 else None
    selected_accession = case.get("selected_accession")
    lookup_accession = selected_accession or case.get("accession", "P00533")
    lookup = {
        "found": True,
        "status": "verified",
        "uniprot_id": lookup_accession,
        "sequence": case.get("reference_sequence_for_lookup"),
    }
    return evidence, chains, selected_chain, (selected_accession, lookup)


def _evaluate_sequence_case(case: dict, root: Path):
    if case["kind"] == "real_pdb":
        pdb_lines = (root / case["path"]).read_text(encoding="utf-8", errors="replace").splitlines()
        evidence = parse_pdb_identity(pdb_lines)
        chains = {case["chain_id"]: extract_pdb_chain_sequence(pdb_lines, case["chain_id"])}
        evidence["chain_sequences"] = chains
        observed = chains[case["chain_id"]]["sequence"]
        reference = case["reference_sequence"]
        accession = case["accession"]
        selected = case["chain_id"]
        selected_accession = None
        lookup = {"found": True, "status": "verified", "uniprot_id": accession, "sequence": reference}
    elif case["kind"] == "metadata":
        reference = synthetic_sequence("curegenix-policy-validation-v1", 500)
        observed = reference
        evidence, chains, selected, lookup_pair = _make_evidence(case, observed)
        if lookup_pair is None:
            selected_accession = None
            lookup = {"found": False, "status": "not_attempted"}
        else:
            selected_accession, lookup = lookup_pair
        accession = selected_accession or case.get("accession")
    else:
        seed = case.get("reference_seed", "curegenix-policy-validation-v1")
        reference = synthetic_sequence(seed, 500)
        observed = transformed_sequence(case, reference)
        if case.get("transform") == "unrelated":
            # A conflict case intentionally uses one sequence as observed and a
            # different reference as the verified PDB-linked accession.
            reference = synthetic_sequence("curegenix-policy-validation-v1", 500)
        evidence, chains, selected, lookup_pair = _make_evidence(case, observed)
        selected_accession, lookup = lookup_pair
        if selected_accession is None and not case.get("dbref_format") and case.get("dbref", True):
            selected_accession = None
        accession = selected_accession or case.get("accession", "P00533")
        lookup["sequence"] = reference

    lookup_accession = accession
    identity = resolve_target_identity(
        evidence, selected, selected_accession, lookup
    )
    validation = None
    resolved_chain = identity.get("selected_chain_id")
    if identity["identity_state"] in {"structure_linked", "externally_verified"}:
        validation = validate_chain_sequence(chains.get(resolved_chain) or {}, reference, SequenceValidationPolicy())
        validation["uniprot_accession"] = identity.get("uniprot_id") or lookup_accession
        if identity["identity_state"] == "structure_linked":
            identity["identity_state"] = validation["identity_state"]
            identity["candidate_generation_allowed"] = validation["candidate_generation_allowed"]
        else:
            identity["candidate_generation_allowed"] = False
        identity["sequence_validation"] = validation

    if case["kind"] == "real_pdb":
        score_policy = SequenceValidationPolicy(
            min_aligned_residues=40,
            min_observed_coverage=0.95,
            min_reference_coverage=0.80,
        )
        diagnostic = validate_chain_sequence(chains[case["chain_id"]], reference, score_policy)
        diagnostic["uniprot_accession"] = accession
    else:
        diagnostic = validation

    expected = case["expected_generation_allowed"]
    sequence_policy_allows = bool(identity.get("candidate_generation_allowed"))
    references, generation_warning = get_target_references(identity)
    actual = sequence_policy_allows and bool(references)
    if case.get("label_confidence") == "source_conflict" or case["kind"] == "real_pdb":
        classification = "diagnostic_only"
    elif expected and actual:
        classification = "expected_allowance"
    elif expected and not actual:
        classification = "false_rejection"
    elif not expected and actual:
        classification = "false_acceptance"
    else:
        classification = "expected_rejection"

    return {
        "case_id": case["case_id"],
        "category": case["category"],
        "kind": case["kind"],
        "relationship": case["relationship"],
        "source_identifier": case.get("source_identifier"),
        "source_urls": case.get("source_urls", []),
        "label_basis": case.get("label_basis", "Constructed from a deterministic synthetic sequence transformation."),
        "label_confidence": case.get("label_confidence", "synthetic_by_construction"),
        "expected_state": case["expected_state"],
        "actual_state": identity["identity_state"],
        "state_matches_expectation": identity["identity_state"] == case["expected_state"],
        "expected_generation_allowed": expected,
        "actual_generation_allowed": actual,
        "sequence_policy_allows_generation": sequence_policy_allows,
        "configured_target_reference_available": bool(references),
        "generation_gate_warning": generation_warning,
        "classification": classification,
        "selected_chain_id": identity.get("selected_chain_id"),
        "uniprot_accession": identity.get("uniprot_id") or lookup_accession,
        "observed_sequence": observed,
        "reference_sequence": reference,
        "observed_sequence_length": len(observed),
        "reference_sequence_length": len(reference),
        "validation": validation,
        "diagnostic_validation": diagnostic if case["kind"] == "real_pdb" else None,
        "identity_warnings": identity.get("warnings", []),
        "unsupported_dbref1_dbref2": any(
            "extended DBREF" in warning for warning in evidence.get("warnings", [])
        ),
    }


def evaluate_cases(manifest: dict, root: Path = ROOT) -> dict:
    policy = SequenceValidationPolicy()
    cases = [_evaluate_sequence_case(case, root) for case in manifest["cases"]]
    scored = [case for case in cases if case["label_confidence"] == "synthetic_by_construction"]
    tp = sum(case["expected_generation_allowed"] and case["actual_generation_allowed"] for case in scored)
    fp = sum(not case["expected_generation_allowed"] and case["actual_generation_allowed"] for case in scored)
    fn = sum(case["expected_generation_allowed"] and not case["actual_generation_allowed"] for case in scored)
    tn = sum(not case["expected_generation_allowed"] and not case["actual_generation_allowed"] for case in scored)
    category_counts = defaultdict(Counter)
    for case in cases:
        category_counts[case["category"]][case["actual_state"]] += 1
    return {
        "schema_version": 1,
        "fixture_manifest": MANIFEST_PATH.relative_to(root).as_posix(),
        "fixture_version": manifest["fixture_version"],
        "evaluation_policy": {
            "source": "explicit SequenceValidationPolicy defaults; environment overrides are not applied",
            "thresholds": {
                "minimum_identity_fraction": policy.min_identity_fraction,
                "minimum_observed_coverage": policy.min_observed_coverage,
                "minimum_reference_coverage": policy.min_reference_coverage,
                "minimum_informative_aligned_residues": policy.min_aligned_residues,
                "maximum_internal_gap_fraction": policy.max_gap_fraction,
            },
            "identity_denominator": "informative aligned residue/residue columns; X/B/Z/J excluded",
            "observed_coverage_denominator": "all observed coordinate residues, including X",
            "reference_coverage_denominator": "all residues in verified UniProt reference sequence",
            "alignment": "affine-gap semi-global Gotoh; match +2, mismatch -2, gap open -5, extension -1; full observed query to reference substring",
        },
        "runtime_versions": {
            "python": platform.python_version(),
            "numpy": np.__version__,
            "rdkit": rdkit.__version__,
        },
        "summary": {
            "total_cases": len(cases),
            "synthetic_scored_cases": len(scored),
            "real_or_source_conflict_diagnostics_excluded_from_performance": len(cases) - len(scored),
            "synthetic_generation_decision_counts": {"true_allow": int(tp), "false_acceptance": int(fp), "false_rejection": int(fn), "true_rejection": int(tn)},
            "state_matches_expected": sum(case["state_matches_expectation"] for case in cases),
            "state_expectations_total": len(cases),
            "by_category": {category: dict(counts) for category, counts in sorted(category_counts.items())},
            "false_acceptance_cases": [case["case_id"] for case in scored if case["classification"] == "false_acceptance"],
            "false_rejection_cases": [case["case_id"] for case in scored if case["classification"] == "false_rejection"],
            "warning": "Synthetic case outcomes measure known software scenarios only and are not estimates of biological sensitivity, specificity, or real-world error rates.",
        },
        "cases": cases,
    }


def _pct(value):
    return "—" if value is None else f"{value * 100:.1f}%"


def _case_markdown(case: dict) -> str:
    validation = case.get("validation") or {}
    gaps = f"{validation.get('insertion_count', 0)} ins / {validation.get('deletion_count', 0)} del"
    identity = validation.get("identity_percent")
    identity_text = f"{identity:.1f}%" if identity is not None else "—"
    return (
        f"| `{case['case_id']}` | {case['category']} | `{case['actual_state']}` | "
        f"{identity_text} "
        f"(n={validation.get('informative_aligned_residues', 0)}) | "
        f"{_pct(validation.get('observed_chain_coverage'))} | "
        f"{_pct(validation.get('reference_sequence_coverage'))} | "
        f"{gaps}; {validation.get('substitution_count', 0)} subst. | "
        f"{str(case['sequence_policy_allows_generation']).lower()} | "
        f"{str(case['expected_generation_allowed']).lower()} / {str(case['actual_generation_allowed']).lower()} | "
        f"{case['classification']} |"
    )


